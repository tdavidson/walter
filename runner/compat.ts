// Build COMPATIBILITY.md from every results/*.json: one column per engine, one row per tag.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = new URL('../results/', import.meta.url).pathname
const reports = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort((a, b) => (a === 'reference.json' ? -1 : b === 'reference.json' ? 1 : a.localeCompare(b)))
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))

const tags = [...new Set(reports.flatMap((r: any) => r.results.flatMap((x: any) => x.tags)))].sort() as string[]
const cell = (r: any, tag: string) => {
  const xs = r.results.filter((x: any) => x.tags.includes(tag))
  if (xs.length === 0) return ''
  const pass = xs.filter((x: any) => x.status === 'pass').length
  const unsup = xs.filter((x: any) => x.status === 'unsupported').length
  return `${pass}/${xs.length}${unsup ? ` (${unsup} unsupported)` : ''}`
}

const lines = [
  '# Compatibility',
  '',
  'Generated by `npm run compat` from the files in `results/`. Each engine runs every vector with',
  '`node runner/run.ts`; a cell is the vectors with that tag it passes. "Unsupported" means the',
  'engine said it cannot express the terms, which is listed rather than counted as a failure.',
  '',
  `| Tag | ${reports.map((r: any) => `${r.engine.name}${r.engine.version ? ` ${r.engine.version}` : ''}`).join(' | ')} |`,
  `| --- | ${reports.map(() => '---').join(' | ')} |`,
  `| **All vectors** | ${reports.map((r: any) => `**${r.summary.pass}/${r.summary.vectors}**`).join(' | ')} |`,
  ...tags.map((t) => `| \`${t}\` | ${reports.map((r: any) => cell(r, t)).join(' | ')} |`),
  '',
]
for (const r of reports) {
  const off = r.results.filter((x: any) => x.status !== 'pass')
  if (off.length === 0) continue
  lines.push(`## ${r.engine.name}: known differences`, '')
  for (const x of off) lines.push(`- \`${x.id}\` (${x.status})${x.problems ? `: ${x.problems[0]}` : ''}`)
  lines.push('')
}
writeFileSync(new URL('../COMPATIBILITY.md', import.meta.url), lines.join('\n'))
console.log(`COMPATIBILITY.md: ${reports.length} engine(s), ${tags.length} tags`)
